#!/usr/bin/env python3
"""Generate compact offline lunar and solar-term tables for the Home app.

Run from the repository root in a development-only environment with
``lunar-python`` installed:

    python tools/generate_home_almanac.py

The generated tables are checked in so firmware builds do not need Python
calendar packages.
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

from lunar_python import Lunar, LunarYear, Solar


FIRST_YEAR = 2023
LAST_YEAR = 2100
OUTPUT = Path("main/apps/home/home_almanac_data.inc")


def day_of_year(solar: Solar, year: int) -> int:
    return (
        date(solar.getYear(), solar.getMonth(), solar.getDay()) - date(year, 1, 1)
    ).days


def pack_terms(year: int, lunar_year: LunarYear) -> list[int]:
    values: list[int] = []
    for index in range(2, 26):  # 小寒 through 冬至, in solar-year order.
        solar = Solar.fromJulianDay(lunar_year.getJieQiJulianDays()[index])
        if solar.getYear() != year:
            raise ValueError(f"solar term outside target year: {year}, {solar.toYmdHms()}")
        values.append(
            day_of_year(solar, year) * 1440
            + solar.getHour() * 60
            + solar.getMinute()
        )

    words: list[int] = []
    pending = 0
    bits = 0
    for value in values:
        pending |= value << bits
        bits += 20
        while bits >= 32:
            words.append(pending & 0xFFFFFFFF)
            pending >>= 32
            bits -= 32
    if bits:
        words.append(pending & 0xFFFFFFFF)
    if len(words) != 15:
        raise ValueError(f"unexpected solar-term word count: {len(words)}")
    return words


def pack_lunar(year: int, lunar_year: LunarYear) -> int:
    new_year = Lunar.fromYmd(year, 1, 1).getSolar()
    months = lunar_year.getMonthsInYear()
    leap = lunar_year.getLeapMonth()
    if not months or not 12 <= len(months) <= 13:
        raise ValueError(f"unexpected lunar month count for {year}: {len(months)}")

    long_months = 0
    for index, month in enumerate(months):
        if month.getDayCount() == 30:
            long_months |= 1 << index
    return (
        day_of_year(new_year, year)
        | (leap << 9)
        | (long_months << 13)
    )


def emit_rows(name: str, rows: list[list[int] | int], width: int | None = None) -> list[str]:
    suffix = f"[{width}]" if width else ""
    lines = [f"static const uint32_t {name}[{len(rows)}]{suffix} = {{"]
    for year, row in zip(range(FIRST_YEAR, LAST_YEAR + 1), rows):
        values = row if isinstance(row, list) else [row]
        rendered = ", ".join(f"0x{value:08x}u" for value in values)
        value_block = f"{{ {rendered} }}" if width else rendered
        lines.append(f"    /* {year} */ {value_block},")
    lines.append("};")
    return lines


def main() -> None:
    term_rows: list[list[int]] = []
    lunar_rows: list[int] = []
    for year in range(FIRST_YEAR, LAST_YEAR + 1):
        lunar_year = LunarYear.fromYear(year)
        term_rows.append(pack_terms(year, lunar_year))
        lunar_rows.append(pack_lunar(year, lunar_year))

    lines = [
        "// Generated by tools/generate_home_almanac.py; do not edit by hand.",
        "// 2023--2100 lunar months and 24 solar terms, China standard time.",
        "",
        "#define HOME_ALMANAC_FIRST_YEAR 2023",
        "#define HOME_ALMANAC_LAST_YEAR 2100",
        "",
    ]
    lines.extend(emit_rows("kSolarTermMinutes", term_rows, width=15))
    lines.append("")
    lines.extend(emit_rows("kLunarYearInfo", lunar_rows))
    lines.append("")
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT} ({FIRST_YEAR}-{LAST_YEAR})")


if __name__ == "__main__":
    main()
