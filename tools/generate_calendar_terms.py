#!/usr/bin/env python3
"""Generate compact 24-solar-term data for the Calendar app.

Run from the repository root in a development-only environment with
``lunar-python`` installed:

    python tools/generate_calendar_terms.py

The generated table is checked in so firmware builds do not need Python
calendar packages.
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

from lunar_python import LunarYear, Solar


FIRST_YEAR = 1900
LAST_YEAR = 2101
OUTPUT = Path("main/apps/calendar/calendar_terms_data.inc")


def day_of_year(year: int, solar: Solar) -> int:
    return (date(solar.getYear(), solar.getMonth(), solar.getDay()) - date(year, 1, 1)).days


def pack_terms(year: int, lunar_year: LunarYear) -> list[int]:
    values: list[int] = []
    for index in range(2, 26):  # 小寒 through 冬至, in solar-year order.
        solar = Solar.fromJulianDay(lunar_year.getJieQiJulianDays()[index])
        if solar.getYear() != year:
            raise ValueError(f"solar term outside target year: {year}, {solar.toYmdHms()}")
        values.append(
            day_of_year(year, solar) * 1440
            + solar.getHour() * 60
            + solar.getMinute()
        )

    words: list[int] = []
    pending = 0
    bits = 0
    for value in values:
        pending |= value << bits
        bits += 20
        while bits >= 32:
            words.append(pending & 0xFFFFFFFF)
            pending >>= 32
            bits -= 32
    if bits:
        words.append(pending & 0xFFFFFFFF)
    if len(words) != 15:
        raise ValueError(f"unexpected solar-term word count: {len(words)}")
    return words


def main() -> None:
    rows: list[list[int]] = []
    for year in range(FIRST_YEAR, LAST_YEAR + 1):
        rows.append(pack_terms(year, LunarYear.fromYear(year)))

    lines = [
        "// Generated by tools/generate_calendar_terms.py; do not edit by hand.",
        "// 1900--2101, 24 solar terms, China standard time.",
        "",
        f"#define CALENDAR_TERM_FIRST_YEAR {FIRST_YEAR}",
        f"#define CALENDAR_TERM_LAST_YEAR {LAST_YEAR}",
        "",
        f"static const uint32_t kCalendarTermMinutes[{len(rows)}][15] = {{",
    ]
    for year, row in zip(range(FIRST_YEAR, LAST_YEAR + 1), rows):
        values = ", ".join(f"0x{value:08x}u" for value in row)
        lines.append(f"    /* {year} */ {{ {values} }},")
    lines += ["};", ""]

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT} ({FIRST_YEAR}-{LAST_YEAR})")


if __name__ == "__main__":
    main()
