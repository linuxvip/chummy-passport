#!/usr/bin/env python3
"""Generate compact lunar-year and solar-term data for the Bazi application.

The runtime never depends on lunar_python. This script uses it only to produce
the checked-in C include. Terms are stored as seconds from January 1 00:00 in
the same calendar year; lunar years store the leap month, long-month bitmap
and Chinese New Year day-of-year.
"""

from datetime import date
from pathlib import Path

from lunar_python import Lunar


FIRST_SOLAR_YEAR = 1899
LAST_SOLAR_YEAR = 2101
FIRST_LUNAR_YEAR = 1899
LAST_LUNAR_YEAR = 2100
JIE_NAMES = [
    "小寒", "立春", "惊蛰", "清明", "立夏", "芒种",
    "小暑", "立秋", "白露", "寒露", "立冬", "大雪",
]


def solar_date(value):
    return date(value.getYear(), value.getMonth(), value.getDay())


def term_seconds(year):
    table = Lunar.fromYmd(year, 6, 1).getJieQiTable()
    start = date(year, 1, 1)
    result = []
    for name in JIE_NAMES:
        value = table[name]
        delta = solar_date(value) - start
        second = delta.days * 86400 + value.getHour() * 3600 + value.getMinute() * 60 + value.getSecond()
        assert 0 <= second < 366 * 86400
        result.append(second)
    assert result == sorted(result)
    return result


def leap_month(year):
    found = 0
    for month in range(1, 13):
        try:
            value = Lunar.fromYmd(year, -month, 1)
        except Exception:
            continue
        if value.getYear() == year and value.getMonth() == -month:
            assert not found
            found = month
    return found


def lunar_year_info(year):
    leap = leap_month(year)
    sequence = []
    for month in range(1, 13):
        sequence.append(month)
        if month == leap:
            sequence.append(-month)

    starts = [solar_date(Lunar.fromYmd(year, month, 1).getSolar())
              for month in sequence]
    next_year = solar_date(Lunar.fromYmd(year + 1, 1, 1).getSolar())
    starts.append(next_year)

    long_bits = 0
    for slot, (start, end) in enumerate(zip(starts, starts[1:])):
        days = (end - start).days
        assert days in (29, 30)
        if days == 30:
            assert slot < 13
            long_bits |= 1 << slot

    new_year = starts[0]
    new_year_doy = (new_year - date(year, 1, 1)).days
    assert 0 <= new_year_doy <= 365
    assert 0 <= leap <= 12
    return leap | (long_bits << 4) | (new_year_doy << 17)


def main():
    root = Path(__file__).resolve().parents[1]
    output = root / "main/apps/bazi/bazi_almanac_data.inc"
    output.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "// Generated by tools/generate_bazi_almanac.py; do not edit by hand.",
        f"#define BAZI_TERM_FIRST_YEAR {FIRST_SOLAR_YEAR}",
        f"#define BAZI_TERM_LAST_YEAR {LAST_SOLAR_YEAR}",
        f"#define BAZI_LUNAR_FIRST_YEAR {FIRST_LUNAR_YEAR}",
        f"#define BAZI_LUNAR_LAST_YEAR {LAST_LUNAR_YEAR}",
        "",
        "static const uint32_t kTermSecondOfYear"
        f"[{LAST_SOLAR_YEAR - FIRST_SOLAR_YEAR + 1}][12] = {{",
    ]
    for year in range(FIRST_SOLAR_YEAR, LAST_SOLAR_YEAR + 1):
        values = ", ".join(f"{value}u" for value in term_seconds(year))
        lines.append(f"    /* {year} */ {{ {values} }},")
    lines += [
        "};",
        "",
        "static const uint32_t kLunarYearInfo"
        f"[{LAST_LUNAR_YEAR - FIRST_LUNAR_YEAR + 1}] = {{",
    ]
    values = [lunar_year_info(year) for year in range(FIRST_LUNAR_YEAR, LAST_LUNAR_YEAR + 1)]
    for offset in range(0, len(values), 8):
        chunk = ", ".join(f"0x{value:08x}u" for value in values[offset:offset + 8])
        lines.append(f"    {chunk},")
    lines += ["};", ""]
    output.write_text("\n".join(lines))
    print(f"Wrote {output} ({output.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
